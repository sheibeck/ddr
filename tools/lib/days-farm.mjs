/** strongerVariant(noStairs, hoarder) — the tie-break order: p90, then unbounded count, then max, then "hoarder". */
function strongerVariant(noStairs, hoarder) {
  if (noStairs.days.p90 !== hoarder.days.p90) return noStairs.days.p90 > hoarder.days.p90 ? "noStairs" : "hoarder";
  if (noStairs.unbounded !== hoarder.unbounded) return noStairs.unbounded > hoarder.unbounded ? "noStairs" : "hoarder";
  if (noStairs.days.max !== hoarder.days.max) return noStairs.days.max > hoarder.days.max ? "noStairs" : "hoarder";
  return "hoarder";
}

/**
 * farmVerdict({honest, farm}) — the mechanical verdict, no judgment call.
 * `honest` is `summarizeHonest` output; `farm` is `{"1": {noStairs, hoarder},
 * "2": {...}}` of `summarizeFarm` output (either floor key may be absent —
 * a single-floor measurement is valid input, just gives `branch: null`).
 *
 * Per measured floor: `stronger` is the tie-broken stronger variant;
 * `capHits` is the SUM of both variants' `unbounded` counts (a cap hit by
 * either variant counts, even if it is not the stronger one — 82-CONTEXT.md:
 * "any farmer run hits the cap"); `wins` is `stronger p90 >= honest.days.p99`
 * OR `capHits > 0`; `reason` names which (or both, or neither) fired.
 *
 * `branch` is set ONLY when both floors are measured (a single-floor
 * measurement returns `branch: null` with `note` naming the missing floor —
 * plan 82-02 always measures both floors, so this only matters for a partial
 * smoke run): a floor-2 win gives `"perFloorCap"`; otherwise a floor-1 win
 * gives `"floor2plus"`; otherwise `"mock"`. The corner case where floor 2
 * wins while floor 1 does NOT is deliberately mapped to `"perFloorCap"` —
 * the planner's reading of 82-CONTEXT.md's open corner case, because
 * `perFloorCap` is the only one of the three rules that actually stops
 * floor-2 farming; the user can overrule this reading before plan 82-02
 * records it.
 */
export function farmVerdict({ honest, farm }) {
  const honestP99 = honest.days.p99;
  const floors = {};
  for (const floorKey of Object.keys(farm)) {
    const { noStairs, hoarder } = farm[floorKey];
    const stronger = strongerVariant(noStairs, hoarder);
    const strongerSummary = stronger === "noStairs" ? noStairs : hoarder;
    const strongerP90 = strongerSummary.days.p90;
    const capHits = noStairs.unbounded + hoarder.unbounded;
    const p90Win = strongerP90 >= honestP99;
    const capWin = capHits > 0;
    const wins = p90Win || capWin;
    const reason = p90Win && capWin ? "both" : p90Win ? "p90>=p99" : capWin ? "capHit" : "none";
    floors[floorKey] = { stronger, strongerP90, capHits, wins, reason };
  }

  let branch = null;
  let note = null;
  if (floors["1"] && floors["2"]) {
    if (floors["2"].wins) branch = "perFloorCap";
    else if (floors["1"].wins) branch = "floor2plus";
    else branch = "mock";
  } else {
    const missing = floors["1"] ? "2" : "1";
    note = `Only floor ${missing === "2" ? "1" : "2"} was measured; floor ${missing} is missing — branch is undecided.`;
  }

  const rule = branch ? DAYS_RULES[branch] : null;
  return {
    honestP99,
    floors,
    branch,
    ruleLine: rule ? rule.ruleLine : null,
    rankKey: rule ? rule.rankKey : null,
    voiceLine: rule ? rule.voiceLine : null,
    note,
  };
}

/**
 * buildFarmReport({meta, honestRows, farmRows}) — assembles the full report:
 * `{meta, honest: {summary, rows}, farm: {F: {V: {summary, rows}}}, verdict}`.
 * `farmRows` is `{"1": {noStairs: rows, hoarder: rows}, ...}` (only the
 * measured floor keys need be present). Plain JSON data only — the whole
 * return value survives a `JSON.parse(JSON.stringify(...))` round trip
 * unchanged.
 */
export function buildFarmReport({ meta, honestRows, farmRows }) {
  const honestSummary = summarizeHonest(honestRows);
  const farm = {};
  const farmSummaries = {};
  for (const floorKey of Object.keys(farmRows)) {
    farm[floorKey] = {};
    farmSummaries[floorKey] = {};
    for (const variant of FARM_VARIANTS) {
      const rows = farmRows[floorKey][variant] || [];
      const summary = summarizeFarm(rows);
      farm[floorKey][variant] = { summary, rows };
      farmSummaries[floorKey][variant] = summary;
    }
  }
  const verdict = farmVerdict({ honest: honestSummary, farm: farmSummaries });
  return { meta, honest: { summary: honestSummary, rows: honestRows }, farm, verdict };
}

/** pct1(ratio) — a 0..1 ratio as a one-decimal percentage string. */
function pct1(ratio) {
  return `${(ratio * 100).toFixed(1)}%`;
}

/**
 * formatFarmReport(report) — the deterministic markdown block the CLI prints
 * and the ledger (docs/DAYS-FARMING.md, plan 82-02) pastes verbatim. No
 * commit hash, no timestamp — the same `report` object always renders the
 * same string. Headings are `###`/`####` only.
 */
export function formatFarmReport(report) {
  const { meta, honest, farm, verdict } = report;
  const lines = [];

  lines.push(
    `*seeds=${meta.seeds} (${meta.seedList})  farmFloors=[${meta.farmFloors.join(",")}]  caps: maxActions=${meta.caps.maxActions} maxDays=${meta.caps.maxDays}  bot: exploreBudget=${meta.bot.exploreBudget} campThreshold=${meta.bot.campThreshold}*`,
  );

  lines.push("");
  lines.push("### Honest baseline");
  lines.push("");
  lines.push("| runs | completed | stuck | days p50 | days p90 | days p99 | days max |");
  lines.push("|---|---|---|---|---|---|---|");
  lines.push(
    `| ${honest.summary.runs} | ${honest.summary.completed} | ${honest.summary.stuck} | ${honest.summary.days.p50} | ${honest.summary.days.p90} | ${honest.summary.days.p99} | ${honest.summary.days.max} |`,
  );
  lines.push("");
  lines.push("| floor-1 deaths n | days p50 | days p90 | days p99 | days max |");
  lines.push("|---|---|---|---|---|");
  lines.push(
    `| ${honest.summary.floor1Deaths.n} | ${honest.summary.floor1Deaths.days.p50} | ${honest.summary.floor1Deaths.days.p90} | ${honest.summary.floor1Deaths.days.p99} | ${honest.summary.floor1Deaths.days.max} |`,
  );

  for (const floorKey of Object.keys(farm).sort()) {
    lines.push("");
    lines.push(`### Farm floor ${floorKey}`);
    lines.push("");
    lines.push(
      "| variant | runs | counted | dead | unbounded (frozen clock) | leftFloor | notReached | days p50 | days p90 | days p99 | days max | starve % | rations bought | cooked | mean hungry nights | camp guard | breaker | boxed in |",
    );
    lines.push("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|");
    for (const variant of FARM_VARIANTS) {
      const s = farm[floorKey][variant].summary;
      lines.push(
        `| ${variant} | ${s.runs} | ${s.counted} | ${s.dead} | ${s.unbounded} (${s.unboundedFrozenClock}) | ${s.leftFloor} | ${s.notReached} | ${s.days.p50} | ${s.days.p90} | ${s.days.p99} | ${s.days.max} | ${pct1(s.starveShare)} | ${s.totals.rationsBought} | ${s.totals.cooked} | ${s.hungryNightsMean} | ${s.totals.campGuard} | ${s.totals.breaker} | ${s.totals.boxedIn} |`,
      );
    }

    const strongerKey = verdict.floors[floorKey] ? verdict.floors[floorKey].stronger : FARM_VARIANTS[0];
    const strongerSummary = farm[floorKey][strongerKey].summary;

    lines.push("");
    lines.push(`#### By race (stronger variant: ${strongerKey})`);
    lines.push("");
    lines.push("| race | n | days p50 | days max | unbounded |");
    lines.push("|---|---|---|---|---|");
    for (const race of Object.keys(strongerSummary.byRace).sort()) {
      const r = strongerSummary.byRace[race];
      lines.push(`| ${race} | ${r.n} | ${r.p50} | ${r.max} | ${r.unbounded} |`);
    }

    lines.push("");
    lines.push(`#### By class (stronger variant: ${strongerKey})`);
    lines.push("");
    lines.push("| class | n | days p50 | days max | unbounded |");
    lines.push("|---|---|---|---|---|");
    for (const cls of Object.keys(strongerSummary.byClass).sort()) {
      const r = strongerSummary.byClass[cls];
      lines.push(`| ${cls} | ${r.n} | ${r.p50} | ${r.max} | ${r.unbounded} |`);
    }
  }

  lines.push("");
  lines.push("### Verdict");
  lines.push("");
  lines.push("| floor | stronger | stronger p90 | honest p99 | cap hits | wins | reason |");
  lines.push("|---|---|---|---|---|---|---|");
  for (const floorKey of Object.keys(verdict.floors).sort()) {
    const f = verdict.floors[floorKey];
    lines.push(`| ${floorKey} | ${f.stronger} | ${f.strongerP90} | ${verdict.honestP99} | ${f.capHits} | ${f.wins} | ${f.reason} |`);
  }
  lines.push("");
  lines.push(`Branch: ${verdict.branch ?? "none"}`);
  lines.push(`Rule: ${verdict.ruleLine ?? verdict.note ?? "no rule (insufficient floors measured)"}`);

  return lines.join("\n");
}
