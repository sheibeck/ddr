export const FARM_CAPS = Object.freeze({ maxActions: 20000, maxDays: 500 });

// FARM_VARIANTS — the two farmer variants the verdict compares; the verdict
// uses whichever is STRONGER (82-CONTEXT.md: "humans play better than the
// bot").
export const FARM_VARIANTS = Object.freeze(["noStairs", "hoarder"]);

// CLOCK_WINDOW — an `unbounded` row's own clockMoving flag (ledger-only; it
// never removes a run from the win count) is true when the last `dayBegan`
// landed within this many actions of the run's end.
export const CLOCK_WINDOW = 2000;

// BREAKER_LIMIT — makeFarmerPolicy's forced-move breaker: this many
// consecutive out-of-combat, no-open-decision, non-move actions force a
// farmer move instead, so a farmer policy can never spin forever on a
// no-op decision loop the fair bot itself would eventually break out of
// with a floor change (which the farmer forbids).
export const BREAKER_LIMIT = 50;

/**
 * isStairsCell(cell) — true for a floor-changing tile. `resolveFeature`
 * (engine/movement.js) is the ONLY caller of `descend()`, and only for
 * `feat === "exit"` (current genFloor output) or the legacy `"gate"` tile
 * (an in-flight save generated by an OLD genFloor, RUN-04 compatibility). A
 * teleport landing never descends, so `"tele"` is not a stairs cell.
 */
export function isStairsCell(cell) {
  return !!cell && (cell.feat === "exit" || cell.feat === "gate");
}

/** destCell(state, dir) — the floor cell one step from the player in `dir`, or null off-grid. */
function destCell(state, dir) {
  const f = state.floor;
  const [dx, dy] = DIRS[dir];
  const row = f.g[f.py + dy];
  return row ? row[f.px + dx] ?? null : null;
}

/** pickAmongLegal(state, policyRng, avoid) — policyRng.pick among legalDirs whose destination fails `avoid`; null when none qualify. */
function pickAmongLegal(state, policyRng, avoid) {
  const dirs = legalDirs(state).filter((dir) => {
    const cell = destCell(state, dir);
    return cell && !avoid(cell);
  });
  return dirs.length ? policyRng.pick(dirs) : null;
}

/**
 * farmDir(state, policyRng) — the farmer's own movement, replacing
 * `decideAction`'s move whenever the fair bot would move on the farm floor
 * (`makeFarmerPolicy` step iv). NEVER returns a direction whose destination
 * is a stairs cell (`isStairsCell`). Goal order (all via `bfsFirstStep`,
 * mirroring `nearestUnseenDir`/`dirTowardExit`'s own two-pass hazard
 * shape):
 *   (a) nearest unseen cell, avoiding stairs and seen hazards;
 *   (b) nearest unseen cell, avoiding stairs only;
 *   (c) nearest seen dot or chest, avoiding stairs and seen hazards —
 *       Claude's Discretion (82-CONTEXT.md): a human farmer takes every
 *       dot, and dots are the only stores;
 *   (d) the same, avoiding stairs only;
 *   (e) a random legal step (policyRng.pick), avoiding stairs and seen
 *       hazards — Claude's Discretion: the wander after the floor is
 *       cleared, a random legal step that never takes the stairs and keeps
 *       the 100-squares day clock moving;
 *   (f) the same, avoiding stairs only;
 *   (g) null (boxed in — every legal step is the stairs).
 */
export function farmDir(state, policyRng) {
  const seenHazard = (cell) => cell.seen && HAZARD_FEATS.has(cell.feat);
  const stairsOrHazard = (cell) => isStairsCell(cell) || seenHazard(cell);
  const stairsOnly = (cell) => isStairsCell(cell);
  const unseenGoal = (cell) => !cell.seen;
  const dotOrChestGoal = (cell) => cell.seen && (cell.feat === "dot" || cell.feat === "chest");

  return (
    bfsFirstStep(state, unseenGoal, stairsOrHazard) ??
    bfsFirstStep(state, unseenGoal, stairsOnly) ??
    bfsFirstStep(state, dotOrChestGoal, stairsOrHazard) ??
    bfsFirstStep(state, dotOrChestGoal, stairsOnly) ??
    pickAmongLegal(state, policyRng, stairsOrHazard) ??
    pickAmongLegal(state, policyRng, stairsOnly) ??
    null
  );
}

/**
 * hoarderStorePick(state) — the hoarder variant's store policy: buy the
 * store's Rations line with all its gold before anything else, every store
 * visit. There is no GOLD_RESERVE (`chooseStorePurchase`'s own reserve,
 * tools/lib/tuning-bot.mjs) — the hoarder spends everything on food. Returns
 * `{type:"buyItem", idx}` for the first `"buyRations"` stock line with stock
 * left (`rationsLeft`) that the engine's own `storeBuyRefusal` lets through
 * (affordable, and not past the pack's ration cap); `null` when there is none
 * or `c.rations` is already at `BAGS[c.bag].rations` (its target).
 *
 * Phase 87 (STORE-04): the engine now sells the Rations line PER RATION (a d10
 * of them per store, `buyFrom` decrements `left`), so this buys ONE ration per
 * purchase and is asked again on each decision, until the cap, the purse or
 * the shelf runs out. The old one-ration-per-visit note is retired. It reads
 * the engine's refusal, so it can never loop on a buy the engine would refuse.
 */
export function hoarderStorePick(state) {
  const st = state.store;
  if (!st || !Array.isArray(st.stock)) return null;
  const c = state.c;
  const cap = BAGS[c.bag] && BAGS[c.bag].rations;
  if (cap !== undefined && c.rations >= cap) return null;
  const idx = st.stock.findIndex((line) => line.effectId === "buyRations" && !line.sold && rationsLeft(line) > 0 && storeBuyRefusal(c, line) === null);
  return idx === -1 ? null : { type: "buyItem", idx };
}

/**
 * makeFarmerPolicy({variant, farmFloor}) — returns `{policy, stats}` for one
 * `playRun` call. `stats` is a mutable `{campGuard, breaker, boxedIn}`
 * accumulator the returned `policy` closure writes into as it runs.
 *
 * `policy(state, policyRng, ctx)`:
 *   - First, `action = decideAction(state, policyRng, ctx)` — the shipped
 *     fair bot, unmodified. This is a WRAP, never a fork. (Phase 87 STORE-04:
 *     the wrapped fair bot now also tops up rations in a store, one per
 *     purchase, after its gear passes — see tuning-bot.mjs#BOT_RATION_DAYS.)
 *   - Below the farm floor (`state.floor.depth < farmFloor`), `action` is
 *     returned unchanged — a farm-floor-2 run descends exactly like the
 *     honest run until it first reaches floor 2.
 *   - On the farm floor, in order:
 *     (i) hoarder variant, and `action` is `buyItem`/`leaveStore` (the fair
 *         bot's own store branch fired): return `hoarderStorePick(state)`,
 *         or `action` when that is `null` (nothing to buy — leave, exactly
 *         like the fair bot);
 *     (ii) `action` is `camp` but `c.rations < nightlyEats(state)`: the
 *         fair bot's own camp gate (tools/lib/tuning-bot.mjs#decideAction)
 *         reads only the HERO's own appetite (`RACES[c.race].eats`), while
 *         `makeCamp` (engine/movement.js) refuses on the PARTY's real
 *         appetite (`nightlyEats`) — the probe's seed-55434 stall. Increment
 *         `stats.campGuard` and return the farmer move instead of a refused
 *         camp the bot would otherwise repeat until `maxActions`;
 *     (iii) the breaker: `BREAKER_LIMIT` consecutive actions taken out of
 *         combat, with no open decision pending (no store, no
 *         `pendingLoot` items, no `pendingJoiner`, no `pendingFind`, no
 *         `pendingHazard`), whose type is not `move` — increment
 *         `stats.breaker`, reset the counter, and return the farmer move.
 *         The counter resets on any `move` action and on any in-combat
 *         action;
 *     (iv) `action` is `move` and there is no combat: return the farmer
 *         move (`farmDir`) instead — this is what keeps the fair bot's own
 *         `dirTowardExit` from ever walking onto the stairs once the floor
 *         is cleared;
 *     (v) anything else (an in-combat action, or an open-decision action
 *         the breaker above exempted): return `action` unchanged.
 *   - The farmer move is `{type:"move", dir: farmDir(state, policyRng)}`.
 *     When `farmDir` returns `null` (boxed in — every legal step is the
 *     stairs), increment `stats.boxedIn` and return `decideAction`'s own
 *     `action` instead — it may take the stairs, and the run is then tagged
 *     `leftFloor` by `playFarmRun`.
 *   - Neither variant ever adds a camp of its own; both camp only when the
 *     fair bot does (`campThreshold`), never to pass time. The policy never
 *     mutates `state`.
 */
export function makeFarmerPolicy({ variant, farmFloor }) {
  const stats = { campGuard: 0, breaker: 0, boxedIn: 0 };
  let noDecisionStreak = 0;

  const farmerMove = (state, policyRng, fallback) => {
    const dir = farmDir(state, policyRng);
    if (dir === null) {
      stats.boxedIn++;
      return fallback; // decideAction's own action — may take the stairs -> leftFloor
    }
    return { type: "move", dir };
  };

  const policy = (state, policyRng, ctx) => {
    const action = decideAction(state, policyRng, ctx);
    if (state.floor.depth < farmFloor) return action;

    const c = state.c;
    const inCombat = !!state.combat;
    const hasOpenDecision =
      !!state.store ||
      (Array.isArray(state.pendingLoot) && state.pendingLoot.length > 0) ||
      !!state.pendingJoiner ||
      !!state.pendingFind ||
      !!state.pendingHazard ||
      !!state.pendingTeleport;

    // (i) hoarder store branch
    if (variant === "hoarder" && (action.type === "buyItem" || action.type === "leaveStore")) {
      noDecisionStreak = 0; // an open decision (the store) — not a breaker tick
      const pick = hoarderStorePick(state);
      return pick ?? action;
    }

    // (ii) camp guard — the fair bot's own gate reads only the hero's
    // appetite; makeCamp refuses on the party's real one (nightlyEats).
    if (action.type === "camp" && c.rations < nightlyEats(state)) {
      stats.campGuard++;
      noDecisionStreak = 0;
      return farmerMove(state, policyRng, action);
    }

    // Reset the breaker on any move or any in-combat action (checked before
    // the breaker itself fires below).
    if (action.type === "move" || inCombat) {
      noDecisionStreak = 0;
    } else if (!hasOpenDecision) {
      // (iii) the breaker: a consecutive out-of-combat, no-open-decision,
      // non-move action.
      noDecisionStreak++;
      if (noDecisionStreak >= BREAKER_LIMIT) {
        stats.breaker++;
        noDecisionStreak = 0;
        return farmerMove(state, policyRng, action);
      }
      return action;
    }

    // (iv) a move with no combat: the farmer's own movement replaces
    // decideAction's (which may head toward the stairs once the floor is
    // cleared).
    if (action.type === "move" && !inCombat) {
      return farmerMove(state, policyRng, action);
    }

    // (v) anything else (in-combat, or an open decision the breaker above
    // exempted) is unchanged.
    return action;
  };

  return { policy, stats };
}

/**
 * playHonestRun(seed) — the fair bot's normal `playRun`, no policy and no
 * stopWhen, so it is byte-identical to `tune-difficulty`'s own run for this
 * seed (proven by Task 3's honest cross-check against
 * `tools/tune-difficulty.mjs`'s `deathDepth`).
 */
export function playHonestRun(seed) {
  let cause = null;
  const run = playRun(seed, { ...BOT_DEFAULTS }, (events) => {
    for (const e of events) if (e.type === "died") cause = e.cause;
  });
  return {
    seed,
    cls: run.state.c.cls,
    sub: run.state.c.sub,
    race: run.state.c.race,
    day: run.state.day,
    floor: run.state.floor.depth,
    actions: run.actions,
    outcome: run.dead ? "dead" : "stuck",
    cause,
  };
}

/**
 * playFarmRun(seed, {variant, farmFloor, maxActions, maxDays}) — plays one
 * farmer run via `playRun`'s Phase 82 hooks: `policy` from
 * `makeFarmerPolicy`, and `stopWhen` ending the run the instant the run
 * would leave the farm floor upward (`depth > farmFloor` — the farmer is
 * never MADE to stop on first arrival at the farm floor, only once it goes
 * past it) or hits `maxDays`. Returns a row with every field set (`null`,
 * never `undefined`, for anything not applicable to this row's outcome).
 */
export function playFarmRun(seed, { variant, farmFloor, maxActions = FARM_CAPS.maxActions, maxDays = FARM_CAPS.maxDays }) {
  const { policy, stats } = makeFarmerPolicy({ variant, farmFloor });

  let reachedFarmAt = farmFloor === 1 ? 0 : null;
  let leftFloor = false;
  let lastDayBeganAt = 0;
  let rationsBought = 0;
  let cooked = 0;
  let hungryNights = 0;
  let campFailed = 0;
  let cause = null;
  let actionCount = 0;

  const stopWhen = (state) => state.floor.depth > farmFloor || state.day >= maxDays;

  const run = playRun(seed, { ...BOT_DEFAULTS, maxActions, policy, stopWhen }, (events, state) => {
    actionCount++;
    if (reachedFarmAt === null && state.floor.depth === farmFloor) reachedFarmAt = actionCount;
    if (state.floor.depth > farmFloor) leftFloor = true;
    for (const e of events) {
      if (e.type === "dayBegan") lastDayBeganAt = actionCount;
      else if (e.type === "rationsBought") rationsBought += e.amount;
      else if (e.type === "cooked") cooked += e.rations;
      else if (e.type === "wentHungry") hungryNights++;
      else if (e.type === "campFailed") campFailed++;
      else if (e.type === "died") cause = e.cause;
    }
  });

  const day = run.state.day;
  const floor = run.state.floor.depth;
  const actions = run.actions;

  let outcome;
  let capBy = null;
  if (reachedFarmAt === null) {
    outcome = "notReached";
  } else if (leftFloor) {
    outcome = "leftFloor";
  } else if (run.dead) {
    outcome = "dead";
  } else {
    outcome = "unbounded";
    capBy = day >= maxDays ? "days" : "actions";
  }
  const clockMoving = outcome === "unbounded" ? actions - lastDayBeganAt <= CLOCK_WINDOW : null;

  return {
    seed,
    variant,
    farmFloor,
    cls: run.state.c.cls,
    sub: run.state.c.sub,
    race: run.state.c.race,
    day,
    floor,
    actions,
    outcome,
    capBy,
    clockMoving,
    cause,
    reachedFarmAt,
    rationsBought,
    cooked,
    hungryNights,
    campFailed,
    campGuard: stats.campGuard,
    breaker: stats.breaker,
    boxedIn: stats.boxedIn,
  };
}

/** daysDistribution(values) — distribution() (tuning-bot) plus p99, never NaN on an empty set. */
function daysDistribution(values) {
  const sorted = [...values].sort((a, b) => a - b);
  return {
    min: sorted[0] ?? 0,
    p50: percentile(sorted, 0.5),
    p90: percentile(sorted, 0.9),
    p99: percentile(sorted, 0.99),
    max: sorted[sorted.length - 1] ?? 0,
  };
}

/** groupDays(rows, keyFn) — {key: {n, p50, max}} over rows' `.day`, sorted key order. */
function groupDays(rows, keyFn) {
  const groups = {};
  for (const r of rows) (groups[keyFn(r)] ??= []).push(r.day);
  const out = {};
  for (const k of Object.keys(groups).sort()) {
    const sorted = [...groups[k]].sort((a, b) => a - b);
    out[k] = { n: sorted.length, p50: percentile(sorted, 0.5), max: sorted[sorted.length - 1] ?? 0 };
  }
  return out;
}

/** groupDaysWithUnbounded(rows, keyFn) — groupDays plus an `unbounded` count per key. */
function groupDaysWithUnbounded(rows, keyFn) {
  const groups = {};
  for (const r of rows) (groups[keyFn(r)] ??= []).push(r);
  const out = {};
  for (const k of Object.keys(groups).sort()) {
    const list = groups[k];
    const sorted = list.map((r) => r.day).sort((a, b) => a - b);
    out[k] = {
      n: list.length,
      p50: percentile(sorted, 0.5),
      max: sorted[sorted.length - 1] ?? 0,
      unbounded: list.filter((r) => r.outcome === "unbounded").length,
    };
  }
  return out;
}

/**
 * summarizeHonest(rows) — `playHonestRun` rows only. `stuck` rows are
 * excluded from `days`/`depth`/`floor1Deaths` (the same HARN-02 bucketing
 * `tune-difficulty` already applies) but counted in `stuck`. `depth` is the
 * same shape/values as `tune-difficulty --json`'s `deathDepth` (both are
 * `distribution()` over completed rows' floor).
 */
export function summarizeHonest(rows) {
  const completed = rows.filter((r) => r.outcome === "dead");
  const stuck = rows.filter((r) => r.outcome === "stuck");
  const floor1 = completed.filter((r) => r.floor === 1);
  return {
    runs: rows.length,
    completed: completed.length,
    stuck: stuck.length,
    days: daysDistribution(completed.map((r) => r.day)),
    depth: distribution(completed.map((r) => r.floor)),
    floor1Deaths: { n: floor1.length, days: daysDistribution(floor1.map((r) => r.day)) },
    byClass: groupDays(completed, (r) => r.cls),
    byRace: groupDays(completed, (r) => r.race),
  };
}

/**
 * summarizeFarm(rows) — `playFarmRun` rows for ONE variant on ONE farm
 * floor. Only `dead` and `unbounded` rows ("counted") feed the DAYS
 * percentiles; `leftFloor` and `notReached` are counted separately, never
 * folded silently into `counted`. Every numeric field is `0` (never `NaN`)
 * on an empty set.
 */
export function summarizeFarm(rows) {
  const dead = rows.filter((r) => r.outcome === "dead");
  const unbounded = rows.filter((r) => r.outcome === "unbounded");
  const counted = [...dead, ...unbounded];
  const leftFloor = rows.filter((r) => r.outcome === "leftFloor").length;
  const notReached = rows.filter((r) => r.outcome === "notReached").length;
  const unboundedFrozenClock = unbounded.filter((r) => r.clockMoving === false).length;
  const starveDeaths = dead.filter((r) => r.cause === "starve").length;
  const starveShare = dead.length ? starveDeaths / dead.length : 0;

  const sumField = (list, field) => list.reduce((s, r) => s + (r[field] || 0), 0);
  const totals = {
    rationsBought: sumField(rows, "rationsBought"),
    cooked: sumField(rows, "cooked"),
    campGuard: sumField(rows, "campGuard"),
    breaker: sumField(rows, "breaker"),
    boxedIn: sumField(rows, "boxedIn"),
  };
  const hungryNightsMean = counted.length ? Math.round((sumField(counted, "hungryNights") / counted.length) * 10) / 10 : 0;

  return {
    runs: rows.length,
    counted: counted.length,
    dead: dead.length,
    unbounded: unbounded.length,
    unboundedFrozenClock,
    leftFloor,
    notReached,
    days: daysDistribution(counted.map((r) => r.day)),
    starveDeaths,
    starveShare,
    totals,
    hungryNightsMean,
    byClass: groupDaysWithUnbounded(counted, (r) => r.cls),
    byRace: groupDaysWithUnbounded(counted, (r) => r.race),
  };
}

